using System.Text;
using YamlDotNet.RepresentationModel;

namespace Harnfig;

internal sealed class LockFileStore
{
    public HarnfigLock? Load(string path)
    {
        if (!File.Exists(path))
        {
            return null;
        }

        var root = YamlHelpers.LoadMapping(File.ReadAllText(path), path);
        YamlHelpers.RequireOnlyKeys(root, path, "version", "skills");

        var version = YamlHelpers.RequiredInt(root, "version", path);
        if (version != 1)
        {
            throw new ConfigurationException($"Unsupported lockfile version '{version}'. Expected version 1.");
        }

        var entries = new List<LockEntry>();
        var sequence = YamlHelpers.RequiredSequence(root, "skills", path);
        for (var index = 0; index < sequence.Children.Count; index++)
        {
            var context = $"{path}.skills[{index}]";
            var mapping = YamlHelpers.Mapping(sequence.Children[index], context);
            YamlHelpers.RequireOnlyKeys(mapping, context, "name", "repo", "path", "ref", "commit", "digest");
            var entry = new LockEntry(
                YamlHelpers.RequiredScalar(mapping, "name", context),
                YamlHelpers.RequiredScalar(mapping, "repo", context),
                ConfigParser.NormalizeSkillPath(YamlHelpers.RequiredScalar(mapping, "path", context)),
                YamlHelpers.RequiredScalar(mapping, "ref", context),
                YamlHelpers.RequiredScalar(mapping, "commit", context),
                YamlHelpers.RequiredScalar(mapping, "digest", context));

            if (entry.Commit.Length != 40 || !entry.Commit.All(Uri.IsHexDigit))
            {
                throw new ConfigurationException($"Commit for lock entry '{entry.Name}' must be a 40-character hexadecimal SHA.");
            }

            if (!entry.Digest.StartsWith("sha256:", StringComparison.Ordinal) || entry.Digest.Length != 71)
            {
                throw new ConfigurationException($"Digest for lock entry '{entry.Name}' must be a SHA-256 digest.");
            }

            entries.Add(entry);
        }

        if (entries.Select(entry => entry.Name).Distinct(StringComparer.Ordinal).Count() != entries.Count)
        {
            throw new ConfigurationException("The lockfile contains duplicate skill names.");
        }

        return new HarnfigLock(version, entries);
    }

    public string Serialize(HarnfigLock lockFile)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Generated by harnfig. Commit this file; do not edit it manually.");
        builder.AppendLine("version: 1");
        builder.AppendLine("skills:");

        foreach (var entry in lockFile.Skills.OrderBy(item => item.Name, StringComparer.Ordinal).ThenBy(item => item.Repo, StringComparer.Ordinal))
        {
            builder.Append("  - name: ").AppendLine(YamlHelpers.Quote(entry.Name));
            builder.Append("    repo: ").AppendLine(YamlHelpers.Quote(entry.Repo));
            builder.Append("    path: ").AppendLine(YamlHelpers.Quote(entry.Path));
            builder.Append("    ref: ").AppendLine(YamlHelpers.Quote(entry.Ref));
            builder.Append("    commit: ").AppendLine(YamlHelpers.Quote(entry.Commit));
            builder.Append("    digest: ").AppendLine(YamlHelpers.Quote(entry.Digest));
        }

        return builder.ToString();
    }
}
